import fs from "node:fs";

function stripModuleSyntax(source) {
  return source
    .replace(/^import[\s\S]*?from\s+["'][^"']+["'];\s*/gm, "")
    .replace(/^export /gm, "");
}

const files = ["js/money.js", "js/catalog.js", "js/store.js", "js/app.js"];
const body = files.map((file) => stripModuleSyntax(fs.readFileSync(file, "utf8"))).join("\n");
fs.writeFileSync(
  "js/pos.iife.js",
  `/* generated by scripts/bundle.mjs — do not edit by hand */\n(() => {\n${body}\n})();\n`,
);
