import fs from "node:fs";

function stripModuleSyntax(source) {
  return source
    .replace(/^import[\s\S]*?from\s+["'][^"']+["'];\s*/gm, "")
    .replace(/^export /gm, "");
}

const files = ["js/money.js", "js/catalog.js", "js/store.js", "js/app.js"];
const body = files.map((file) => stripModuleSyntax(fs.readFileSync(file, "utf8"))).join("\n");
const iife = `/* generated by scripts/bundle.mjs — do not edit by hand */\n(() => {\n${body}\n})();\n`;
fs.writeFileSync("js/pos.iife.js", iife);

const html = fs.readFileSync("index.html", "utf8");
const css = fs.readFileSync("css/pos.css", "utf8");
const standalone = html
  .replace('<link rel="icon" href="./favicon.svg" type="image/svg+xml" />\n    ', "")
  .replace('<link rel="stylesheet" href="./css/pos.css" />', `<style>\n${css}\n</style>`)
  .replace('<script src="./js/pos.iife.js"></script>', `<script>\n${iife}\n</script>`);
fs.writeFileSync("app.html", standalone);
