import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import path from "node:path";
import { fileURLToPath } from "node:url";
import "./scale.js";
import "./restaurant.js";
import "./aggregator.js";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const read = (name) => readFileSync(path.join(root, name), "utf8");
const S = globalThis.POSScale;
const R = globalThis.POSRestaurant;
const A = globalThis.POSAggregator;

test("hardware and optional integrations stay off until explicitly enabled", () => {
  assert.equal(S.loadSettings("new-shop").enabled, false);
  assert.equal(R.tableShiftingOn({}), false);
  assert.equal(R.tableShiftingOn({ table_shifting_enabled: 0 }), false);
  assert.equal(R.tableShiftingOn({ table_shifting_enabled: 1 }), true);
  assert.equal(A.isLive("zomato", { zomato_allowed: 0, zomato_enabled: 1 }), false);
  assert.equal(A.isLive("swiggy", { swiggy_allowed: 1, swiggy_enabled: 0 }), false);
  assert.match(read("server/onboard.js"), /INSERT INTO pos_devices[\s\S]*'inactive'/);
  assert.match(read("pos-php-core.php"), /INSERT INTO pos_devices[\s\S]*'inactive'/);
  assert.match(read("server/schema.js"), /scale_enabled.*DEFAULT 0/);
  assert.match(read("server/schema.js"), /camera_scanner_enabled.*DEFAULT 0/);
  assert.match(read("server/schema.js"), /purchase_barcode_enabled.*DEFAULT 0/);
  assert.match(read("server/schema.js"), /recurring_invoices_enabled.*DEFAULT 0/);
  assert.match(read("server/schema.js"), /invoice_signature_enabled.*DEFAULT 0/);
  assert.match(read("server/schema.js"), /invoice_stamp_enabled.*DEFAULT 0/);
  assert.match(read("server/schema.js"), /barcode_tracked.*DEFAULT 0/);
  assert.match(read("server/schema.js"), /receipt_printer_enabled.*DEFAULT 0/);
  assert.match(read("server/schema.js"), /cash_drawer_enabled.*DEFAULT 0/);
  assert.match(read("server/tenant.js"), /status === "active" \? "active" : "inactive"/);
  assert.match(read("server/tenant.js"), /Number\(co\?\.table_shifting_enabled\) === 1/);
});

